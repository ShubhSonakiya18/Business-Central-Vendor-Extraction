"""Test the §24 validation_engine.py against three real sources in this
codebase, and produce a results report.

  SOURCE A -- address_vendor_lines.yaml (20 real industrial vendor addresses,
              hand-authored expectations, multiline convention). For each
              case: run the PRODUCTION resolve_address_blob (the real
              system this validation engine is designed to wrap), then run
              the candidate through validate(). Compare verdict against
              whether resolve_address_blob's own output matched the hand-
              written expectation (known from the existing eval harness).

  SOURCE B -- address_holdout_cases.yaml (30 frozen held-out cases, never
              tuned against -- see docs/ADDRESS_SEGMENTATION_RESEARCH.md
              §12/§23 for why this matters: a fair test needs cases the
              validation engine's own thresholds were not shaped by).

  SOURCE C -- 2,000-row random sample of the 100k-row Excel corpus this
              research is built on, comparing the PRODUCTION segmenter's
              output against the Excel ground truth via a REFERENCE
              candidate cross-check (Step 5), since the Excel ground truth
              itself is NOT a reliable target (§4/§12 of the report) -- this
              tests the validation engine's DISAGREEMENT DETECTION, not
              "does it match the Excel file," which the report already
              proved is the wrong question.

  SOURCE D -- deliberately corrupted variants of Source A (missing token,
              reordered, PIN changed, boundary shift vs reference) to
              confirm the hard-fail gates actually fire on real address
              text, not just the synthetic toy strings in the sanity check.

Output: research/address_segmentation_boundary/output/validation_report.md
"""
from __future__ import annotations

